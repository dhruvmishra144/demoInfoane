import Link from "next/link";

/**
 * Wordmark: the emblem followed by "INFOANE", drawn as one SVG.
 *
 * It fills with currentColor, so the theme only has to set the text colour.
 * The link carries the name as its accessible label, since the lettering is
 * paths rather than text.
 */
export function Logo({
  theme = "light",
  withTagline = false,
  name = "Infoane",
  tagline = "Develop · Support · 24×7",
}: {
  theme?: "light" | "dark";
  withTagline?: boolean;
  name?: string;
  tagline?: string;
}) {
  return (
    <Link
      href="/"
      className={`group inline-flex flex-col leading-none ${
        theme === "dark" ? "text-white" : "text-ink-900"
      }`}
      aria-label={`${name} home`}
    >
      <LogoMark className="h-7 w-auto shrink-0 transition-opacity duration-300 group-hover:opacity-80" />
      {withTagline && tagline && (
        <span
          className={`mt-2 text-xs font-semibold uppercase tracking-[0.18em] ${
            theme === "dark" ? "text-brand-200" : "text-brand-600"
          }`}
        >
          {tagline}
        </span>
      )}
    </Link>
  );
}

